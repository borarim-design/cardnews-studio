export function getTheme(id: string): Theme {
  return THEMES.find((t) => t.id === id) ?? THEMES[0];
}

/** 새 장에 넣을 스타일 = 테마 스타일 사본 (사진 배경은 유지 옵션) */
export function styleFromTheme(themeId: string): CardStyle {
  const t = getTheme(themeId);
  return { ...t.style, photo: null };
}
